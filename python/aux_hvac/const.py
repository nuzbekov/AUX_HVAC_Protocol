# -*- coding: utf-8 -*-
"""Константы и перечисления UART-протокола кондиционеров AUX.

Все значения взяты из README этого репозитория. Ссылки на разделы README
приведены в docstring'ах соответствующих сущностей.
"""

from __future__ import annotations

from enum import IntEnum

__all__ = [
    "START_BYTE",
    "HEADER_LEN",
    "CRC_LEN",
    "MIN_PACKET_LEN",
    "MAX_PACKET_LEN",
    "UART_BAUDRATE",
    "UART_PARITY",
    "UART_BYTESIZE",
    "UART_STOPBITS",
    "PING_PERIOD",
    "WIFI_FLAG_MODULE",
    "WIFI_FLAG_AC",
    "PacketType",
    "Command",
    "Mode",
    "FanSpeed",
    "RealFanSpeed",
    "VerticalLouver",
    "HorizontalLouver",
    "ERROR_CODES",
]

#: Стартовый байт любого пакета (README: «Байт 0, START»).
START_BYTE = 0xBB

#: Длина заголовка пакета в байтах.
HEADER_LEN = 8

#: Длина контрольной суммы в байтах.
CRC_LEN = 2

#: Минимально возможная длина пакета (заголовок + CRC, тело нулевой длины).
MIN_PACKET_LEN = HEADER_LEN + CRC_LEN

#: Максимальная известная длина пакета. 34 байта для всех известных команд,
#: 35 байт для Royal Clima (в конец тела добавлен лишний нулевой байт).
MAX_PACKET_LEN = 35

# --- параметры физического уровня (README: «Параметры UART») ---------------
UART_BAUDRATE = 4800
UART_PARITY = "E"       # even
UART_BYTESIZE = 8
UART_STOPBITS = 1

#: Период дежурных ping-пакетов кондиционера, секунды.
PING_PERIOD = 2.963

# --- байт 3 заголовка (README: «Байт 3, wifi?») ----------------------------
#: Пакет отправлен wifi-модулем (исходящий, [=>]).
WIFI_FLAG_MODULE = 0x80
#: Пакет отправлен кондиционером (входящий, [<=]).
WIFI_FLAG_AC = 0x00


class PacketType(IntEnum):
    """Байт 2 заголовка, TYPE (README: «Типы пакетов»)."""

    PING = 0x01
    """Дежурный пакет. Кондиционер шлёт его сам, модуль отвечает тем же типом."""

    CMD = 0x06
    """Команда/запрос кондиционеру. Всегда исходящий."""

    INFO = 0x07
    """Информационный пакет кондиционера. Всегда входящий."""

    INIT = 0x09
    """Инициирование wifi-модуля (8 нажатий HEALTH за 10 сек)."""

    UNKNOWN_0B = 0x0B
    """Назначение не расшифровано. Модуль шлёт тройками, кондиционер игнорирует."""

    @classmethod
    def _missing_(cls, value):  # pragma: no cover - защита от неизвестных типов
        return None


class Command(IntEnum):
    """Байт 8 пакета TYPE=0x06 и байт 9 пакета TYPE=0x07 (CMD)."""

    CONTROL = 0x01
    """Команда управления. Тело идентично телу INFO/CMD=0x11 (13 байт полезных)."""

    INDOOR = 0x11
    """Запрос/ответ статуса внутреннего блока."""

    OUTDOOR = 0x21
    """Запрос/ответ статуса внешнего блока."""


#: Дежурное информирование: кондиционер раз в 10 минут шлёт INFO с CMD из
#: диапазона 0x20..0x2F. Тело совпадает с телом ответа на CMD=0x21.
PERIODIC_OUTDOOR_CMD_RANGE = range(0x20, 0x30)


class Mode(IntEnum):
    """Режим работы сплита.

    Значение — это биты MD3..MD1, сдвинутые вправо на 5
    (README: «Байт 15 (MO)» пакета CMD=0x11).
    """

    AUTO = 0b000
    COOL = 0b001
    DRY = 0b010
    HEAT = 0b100
    FAN = 0b110


class FanSpeed(IntEnum):
    """Заданная скорость вентилятора: биты SP3..SP1 >> 5.

    README: «Байт 13 (SP+TH)» пакета CMD=0x11.
    AUTO поддерживается в COOL, но отсутствует в режиме FAN.
    """

    AUTO = 0b101
    HIGH = 0b001
    MEDIUM = 0b010
    LOW = 0b011


class RealFanSpeed(IntEnum):
    """Фактическая (а не заданная) скорость вентилятора.

    README: «Байт 13 (FSPD)» пакета CMD=0x21. Значения актуальны только для
    ответов на запрос модуля; в дежурных пакетах тут другие значения.
    """

    OFF = 0x00
    CLEAN = 0x01
    LOW = 0x02
    MID = 0x04
    HIGH = 0x06
    TURBO = 0x07


class VerticalLouver(IntEnum):
    """Положение вертикальных шторок: биты UD3..UD1 байта 10 (TS)."""

    SWING = 0b000
    """Старт качания вверх-вниз."""

    TOP = 0b001
    TOP_MIDDLE = 0b010
    MIDDLE = 0b011
    BOTTOM_MIDDLE = 0b100
    BOTTOM = 0b101
    STOP = 0b111
    """Остановить шторки в текущем положении."""


class HorizontalLouver(IntEnum):
    """Горизонтальные шторки: биты LR3..LR1 байта 11 (SL) >> 5.

    ВНИМАНИЕ: поведение отличается у разных производителей (README, «Байт 11»).
    Для AUX и большинства систем значим только бит LR1:
    0 — качание влево-вправо включено, 1 — выключено.
    Для Rovex/Royal Clima качание включено при LR1=LR2=LR3=0.
    """

    SWING = 0b000
    """Качание влево-вправо включено."""

    OFF = 0b111
    """Качание выключено (Rovex/Royal Clima)."""

    OFF_AUX = 0b001
    """Качание выключено (AUX и большинство систем: значим только LR1)."""


#: Байт 29 пакета CMD=0x21. Расшифровка неполная: достоверно известен только
#: код 0x07. Остальные коды приведены в README как справочная информация
#: и в таблицу намеренно не занесены.
ERROR_CODES = {
    0x00: "нет ошибки",
    0x07: "E5: неисправность внешнего блока",
    0x0E: "E4: нет обратной связи двигателя вентилятора (PG motor feedback)",
}
