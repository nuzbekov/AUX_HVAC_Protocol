# -*- coding: utf-8 -*-
"""Кодек RS485-шины AUX.

Кадровый уровень **расшифрован** по дампу шины контроллера фанкойла AUX.
Смысл полезной нагрузки — пока нет; см. «Что ещё не известно» ниже.

Это отдельный от UART протокол
==============================

Общего с протоколом wifi-модуля (:mod:`aux_hvac.packet`) у него нет ничего:
другой стартовый байт, другая контрольная сумма, другая структура тела.
Проверялось прямо: 13-байтовое тело статуса внутреннего блока
(:class:`aux_hvac.state.IndoorState`) не укладывается ни в один срез
нагрузки — разбор даёт заведомый мусор вида «режим 0x07, вентилятор 0x07,
таймер 28:16». Поэтому классы состояния UART здесь не переиспользуются.

Формат кадра
============

::

    7E  A  B  CMD  LEN  <нагрузка>  CRC_lo CRC_hi
    |   |  |  |    |                |
    |   |  |  |    |                +-- CRC16/MODBUS, младший байт первым
    |   |  |  |    +------------------- длина ВСЕГО кадра, включая 7E и CRC
    |   |  |  +------------------------ код команды
    |   +--+--------------------------- два адреса, см. ниже
    +---------------------------------- стартовый байт

* **параметры линии** — 9600/8-N-1. Подтверждено тем, что на этой скорости
  все 65 кадров дампа сошлись по CRC;
* **CRC16/MODBUS** (отражённый полином 0xA001, начальное значение 0xFFFF,
  без финального XOR) считается от байта **сразу после** ``0x7E`` и до
  байтов CRC, передаётся младшим байтом вперёд. Сошлось 65 из 65 кадров —
  это и есть проверка гипотезы, ради которой в прежней заготовке лежал
  список кандидатов;
* **LEN** — длина всего кадра, вместе со стартовым байтом и CRC. Теоретический
  минимум 7 байт, в дампе минимум 10.

Обратите внимание на разный порядок байт: CRC — little-endian, а 16-битные
значения в нагрузке (см. :class:`RegisterBlock`) — big-endian. Это не
опечатка, так в линии.

Нагрузка: блок регистров
========================

У всех кадров, которые несут данные, нагрузка устроена одинаково::

    <индекс> <кол-во> <кол-во 16-битных значений big-endian>

то есть ``len(payload) == 2 + 2 * count``. Сходится точно на всех кадрах с
данными, в том числе на самом большом: индекс 3, 17 регистров, 2 + 34 = 36
байт.

Значения — знаковые, в десятых долях градуса. Значение ``-100.8`` в
регистре 7, судя по всему, означает «датчик не подключён»: на стенде часть
датчиков действительно не подключена.

Два регистра кадра ``CMD=0x02`` расшифрованы опытом, см.
:data:`KNOWN_REGISTERS`:

* **регистр 13 — датчик ``PIPE``** (теплообменник). Датчик прогрели
  строительным феном, и между двумя дампами шины поехал ровно один регистр:
  ``24.7 -> 74.0``. Ни один другой регистр при этом не изменился;
* **регистр 10 — датчик ``ROOM``** (комната). За те же записи гулял в
  пределах ``24.9..25.3`` — так ведёт себя живой датчик комнаты, а не
  константа.

Заодно выяснилось, что **по этой шине температура теплообменника отдаётся с
разрешением 0,1 градуса**, тогда как в UART-протоколе wifi-модуля тот же
датчик лежит в байте 17 с разрешением 1 градус. Если нужны десятые доли,
брать их надо с RS485.

Остальные регистры за оба опыта не изменились, поэтому имён у них нет:
``11`` и ``12`` держат ``20.0`` и похожи на уставку, ``4``, ``5`` и ``6``
держат ``29.0``, ``32.0`` и ``19.2`` и похожи на границы диапазонов, но это
догадки, и в :data:`KNOWN_REGISTERS` они не занесены.

Короткие кадры ``CMD=0x55`` с нагрузкой ``00 00 11`` под эту модель не
подходят — вышло бы «ноль регистров», но остаётся третий байт. Похоже, это
опрос или keepalive со своим форматом.

Адреса
======

В дампе встретились ``F1``, ``F0``, ``E1``, ``C1``, ``C2``, ``CF``, ``01``,
``00``. Старший полубайт похож на класс устройства, младший — на номер
экземпляра: ``C1``/``C2``/``CF`` и ``F0``/``F1`` идут группами.

В парах запрос-ответ адреса меняются местами (``F1 01`` → ``01 F1``), но
**какой из двух байт источник, а какой получатель, пока не определено.**
Мешает один кадр: во всём цикле опроса первым байтом идёт ``F1``, и только
у опроса адреса ``E1`` первым стоит ``01``. Обе трактовки объясняют цикл
одинаково плохо, поэтому поля названы нейтрально:
:attr:`~RS485Frame.addr_a` и :attr:`~RS485Frame.addr_b`.

Наблюдённый цикл обмена
=======================

Цикл повторяется без изменений (в дампе 6 раз, период 380 байт)::

    F1 01  CMD=55   опрос
    01 F1  CMD=02   ответ: 17 регистров, среди них температуры
    F1 00  CMD=A1
    F1 F1  CMD=12   три кадра: блоки регистров с индексами 10, 23 и 46
    F1 F0  CMD=A5
    01 E1  CMD=55   опрос
    F1 C1  CMD=55   опрос
    F1 C2  CMD=55   опрос
    F1 CF  CMD=55   опрос
    F1 01  CMD=55   опрос
    01 F1  CMD=01   короткий ответ

Отвечает только адрес ``01``, остальные опрашиваемые молчат — на стенде их
физически нет.

Что ещё не известно
===================

1. **Смысл остальных регистров.** Способ известен и уже сработал на
   регистрах 10 и 13: снять два дампа, до и после изменения **одной**
   величины, и сравнить их командой ``aux_tool.py rs485 до.bin --diff
   после.bin``. Осталось перебрать так уставку, режим, скорость вентилятора
   и датчик ``ROOM``. По одному дампу смысл регистра определить нельзя:
   дамп шины — это один и тот же цикл, повторённый много раз.
2. **Кто источник, а кто получатель** в паре адресов — см. выше.
3. **Смысл команд.** ``0x55`` — опрос, ``0x01`` и ``0x02`` — ответы разной
   длины, ``0x12``, ``0xA1``, ``0xA5`` — передача блоков регистров.
   Направление и назначение передачей не проверялись.
4. **Запись.** Есть ли команда записи регистра — неизвестно. Поэтому
   :func:`request_status` кадр собирает (формат-то известен), а функций
   управления здесь нет вовсе: угадывать код команды, которая что-то меняет
   в контроллере, — плохая идея.

Артефакты линии
===============

Перед каждым ответом адреса ``01`` в дампе стоит одиночный байт ``0xFE``, не
входящий ни в один кадр. Похоже на огрызок от переключения направления
RS485: передатчик поднимает драйвер чуть позже начала стартового бита, и
приёмник видит обрубок. Сами кадры при этом целы, CRC сходится.
:class:`RS485Decoder` считает такие байты в :attr:`~RS485Decoder.dropped_bytes`.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional

__all__ = [
    "RS485Frame",
    "RS485Decoder",
    "RegisterBlock",
    "crc16_modbus",
    "request_status",
    "parse_status",
    "FRAME_START",
    "MIN_FRAME_LEN",
    "HEADER_LEN",
    "KNOWN_ADDRESSES",
    "SENSOR_ABSENT",
    "KNOWN_REGISTERS",
    "NotDecodedYet",
]

#: Стартовый байт кадра.
FRAME_START = 0x7E

#: Длина заголовка: стартовый байт, два адреса, команда, длина.
HEADER_LEN = 5

#: Заголовок плюс CRC — короче кадра быть не может.
MIN_FRAME_LEN = HEADER_LEN + 2

#: Адреса, встреченные в дампе. Назначение не установлено.
KNOWN_ADDRESSES = (0x00, 0x01, 0xC1, 0xC2, 0xCF, 0xE1, 0xF0, 0xF1)

#: Значение регистра, похожее на «датчик не подключён»: -100,8 градуса.
SENSOR_ABSENT = -1008

#: Расшифрованные регистры: (команда, номер регистра) -> название.
#:
#: Ключ включает команду не для красоты: блоки регистров разных команд
#: перекрываются по номерам. Так, кадр ``CMD=0x12`` тоже содержит регистры
#: 10..13, но они там нулевые, и подписывать их как датчики нельзя.
#:
#: Здесь только то, что подтверждено опытом «изменили одну величину и
#: сравнили дампы». Догадки сюда не заносятся.
KNOWN_REGISTERS = {
    (0x02, 10): "ROOM, датчик комнаты",
    (0x02, 13): "PIPE, датчик теплообменника",
}


class NotDecodedYet(NotImplementedError):
    """Часть протокола ещё не расшифрована.

    Отдельный тип исключения нужен, чтобы вызывающий код мог отличить
    «эта ветка протокола неизвестна» от «здесь баг».
    """


def crc16_modbus(data: bytes) -> int:
    """CRC16/MODBUS: отражённый полином 0xA001, начальное значение 0xFFFF.

    Считается от байта после :data:`FRAME_START` и до байтов CRC. В линию
    уходит младшим байтом вперёд.
    """
    crc = 0xFFFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc


@dataclass
class RegisterBlock:
    """Блок 16-битных регистров из нагрузки кадра.

    Нагрузка кадров с данными устроена как ``<индекс> <кол-во> <значения>``,
    значения — знаковые big-endian. Смысл конкретных регистров неизвестен,
    поэтому класс не даёт им имён: только индексы и значения.
    """

    index: int
    """Индекс первого регистра в блоке."""

    values: List[int] = field(default_factory=list)
    """Значения регистров, знаковые."""

    @property
    def count(self) -> int:
        return len(self.values)

    @staticmethod
    def as_celsius(value: int) -> Optional[float]:
        """Значение как температура в десятых долях, если оно правдоподобно.

        ГИПОТЕЗА. Возвращает None для :data:`SENSOR_ABSENT` и для значений
        вне разумного диапазона — то есть там, где регистр, похоже, вообще
        не температура.
        """
        if value == SENSOR_ABSENT or not -1000 <= value <= 1000:
            return None
        return value / 10.0

    def items(self):
        """Пары «индекс регистра, значение»."""
        return [(self.index + n, v) for n, v in enumerate(self.values)]

    @classmethod
    def parse(cls, payload: bytes) -> Optional["RegisterBlock"]:
        """Разбирает нагрузку как блок регистров.

        Возвращает None, если нагрузка под модель не подходит: значит это
        кадр другого вида (например, опрос ``CMD=0x55``), и придумывать ему
        регистры не нужно.
        """
        if len(payload) < 2:
            return None
        index, count = payload[0], payload[1]
        if count == 0 or len(payload) != 2 + 2 * count:
            return None
        body = payload[2:]
        values = [
            int.from_bytes(body[k:k + 2], "big", signed=True)
            for k in range(0, len(body), 2)
        ]
        return cls(index=index, values=values)

    def encode(self) -> bytes:
        """Собирает нагрузку обратно."""
        if len(self.values) > 0xFF:
            raise ValueError("регистров больше 255 — не влезут в байт количества")
        out = bytearray([self.index & 0xFF, len(self.values)])
        for value in self.values:
            out.extend(int(value).to_bytes(2, "big", signed=True))
        return bytes(out)

    def describe(self, cmd: Optional[int] = None) -> str:
        """Строка с регистрами. С ``cmd`` подписывает расшифрованные регистры.

        Команда нужна именно для подписи: номера регистров у разных команд
        перекрываются, см. :data:`KNOWN_REGISTERS`.
        """
        parts = []
        for reg, value in self.items():
            temp = self.as_celsius(value)
            name = KNOWN_REGISTERS.get((cmd, reg)) if cmd is not None else None
            text = "%d=%d" % (reg, value)
            if temp is not None:
                text += " (%.1f)" % temp
            if name is not None:
                text += " [%s]" % name
            parts.append(text)
        return "рег %d..%d: %s" % (
            self.index, self.index + self.count - 1, ", ".join(parts))


@dataclass
class RS485Frame:
    """Кадр RS485-шины AUX.

    Кадровый уровень расшифрован полностью, поэтому все поля заголовка
    достоверны. Не расшифрован смысл: что означают адреса, команды и
    регистры — см. docstring модуля.
    """

    addr_a: int
    """Первый адрес заголовка. Источник это или получатель — не установлено."""

    addr_b: int
    """Второй адрес заголовка."""

    cmd: int
    """Код команды."""

    payload: bytes = b""
    """Нагрузка без заголовка и CRC."""

    crc: int = 0
    """CRC, как она пришла из линии."""

    crc_ok: bool = False
    """Сошлась ли контрольная сумма."""

    raw: bytes = b""
    """Байты кадра как они пришли из линии."""

    @property
    def block(self) -> Optional[RegisterBlock]:
        """Нагрузка как блок регистров или None, если она другого вида."""
        return RegisterBlock.parse(self.payload)

    def describe(self) -> str:
        from .packet import hexdump

        head = "RS485 %02X %02X cmd=%02X len=%d" % (
            self.addr_a, self.addr_b, self.cmd, len(self.raw))
        if not self.crc_ok:
            head += " CRC НЕ СОШЛАСЬ"
        block = self.block
        if block is not None:
            return "%s | %s" % (head, block.describe(self.cmd))
        return "%s | %s" % (head, hexdump(self.payload) or "нагрузки нет")

    @classmethod
    def decode(cls, frame: bytes) -> "RS485Frame":
        """Разбирает готовый кадр целиком, вместе со стартовым байтом.

        :raises ValueError: если кадр короче минимального или не начинается
            со :data:`FRAME_START`.
        """
        if len(frame) < MIN_FRAME_LEN:
            raise ValueError("кадр короче %d байт" % MIN_FRAME_LEN)
        if frame[0] != FRAME_START:
            raise ValueError("кадр не начинается с 0x%02X" % FRAME_START)
        crc = frame[-2] | (frame[-1] << 8)
        return cls(
            addr_a=frame[1],
            addr_b=frame[2],
            cmd=frame[3],
            payload=bytes(frame[HEADER_LEN:-2]),
            crc=crc,
            crc_ok=crc16_modbus(frame[1:-2]) == crc,
            raw=bytes(frame),
        )

    def encode(self) -> bytes:
        """Собирает кадр байт в байт: заголовок, нагрузка, CRC.

        Длину считает сама, подделать её нельзя — и это к лучшему: приёмник
        нарезает поток именно по ней.
        """
        total = HEADER_LEN + len(self.payload) + 2
        if total > 0xFF:
            raise ValueError("кадр длиной %d байт не влезает в байт длины" % total)
        head = bytes([FRAME_START, self.addr_a, self.addr_b, self.cmd, total])
        crc = crc16_modbus(head[1:] + bytes(self.payload))
        return head + bytes(self.payload) + bytes([crc & 0xFF, crc >> 8])


class RS485Decoder:
    """Потоковый разборщик шины RS485.

    Нарезает поток по стартовому байту и полю длины — так же, как это делает
    контроллер. Устойчив к мусору: байт, который не может начать корректный
    кадр, отбрасывается по одному, и разбор продолжается с ближайшего
    следующего :data:`FRAME_START`. Так переживаются огрызки от переключения
    направления линии (см. docstring модуля).

    Интерфейс намеренно совпадает с прежней заготовкой, чтобы вызывающий код
    не менялся: :meth:`feed` отдаёт готовые кадры, :meth:`flush` — остаток.
    """

    #: Больше этого в буфере не копим: максимальный кадр всё равно 255 байт.
    MAX_BUFFER = 1024

    def __init__(self, gap_bytes: int = 4) -> None:
        self.gap_bytes = gap_bytes
        """Оставлено для совместимости: нарезка идёт по длине, не по паузе."""
        self._buf = bytearray()
        self.frames_seen = 0
        self.bad_crc = 0
        self.dropped_bytes = 0

    def reset(self) -> None:
        self._buf.clear()

    def feed(self, data: bytes) -> List[RS485Frame]:
        """Скармливает порцию байтов, возвращает разобранные кадры."""
        self._buf.extend(data)
        frames: List[RS485Frame] = []

        while self._buf:
            # ищем стартовый байт, всё до него — мусор
            if self._buf[0] != FRAME_START:
                start = self._buf.find(FRAME_START)
                if start < 0:
                    self.dropped_bytes += len(self._buf)
                    self._buf.clear()
                    break
                self.dropped_bytes += start
                del self._buf[:start]
                continue

            if len(self._buf) < HEADER_LEN:
                break  # байт длины ещё не пришёл

            total = self._buf[4]
            if total < MIN_FRAME_LEN or total > self.MAX_BUFFER:
                # длина заведомо неверная: значит это был не стартовый байт
                self.dropped_bytes += 1
                del self._buf[0]
                continue

            if len(self._buf) < total:
                break  # кадр ещё не дочитан

            frame = RS485Frame.decode(bytes(self._buf[:total]))
            if not frame.crc_ok:
                # CRC не сошлась: скорее всего 0x7E был байтом данных.
                # Отбрасываем его и пробуем разобраться со следующего байта.
                self.bad_crc += 1
                self.dropped_bytes += 1
                del self._buf[0]
                continue

            del self._buf[:total]
            self.frames_seen += 1
            frames.append(frame)

        if len(self._buf) > self.MAX_BUFFER:
            self.dropped_bytes += len(self._buf)
            self._buf.clear()

        return frames

    def flush(self) -> List[RS485Frame]:
        """Досбор по паузе в линии.

        Нарезка идёт по длине, так что паузы дожидаться не нужно и здесь
        обычно пусто. Метод оставлен, чтобы недочитанный хвост не терялся
        молча: он уходит в :attr:`dropped_bytes`.
        """
        if self._buf:
            self.dropped_bytes += len(self._buf)
            self._buf.clear()
        return []


def request_status(addr_a: int = 0xF1, addr_b: int = 0x01) -> bytes:
    """Собирает кадр опроса ``CMD=0x55`` — тот самый, что шлёт мастер в дампе.

    Формат кадра известен, а смысл адресов нет, поэтому «кому» задаётся
    двумя байтами как есть. При значениях по умолчанию кадр получается байт
    в байт таким же, как наблюдённый в линии опрос адреса ``01``.
    """
    return RS485Frame(addr_a=addr_a, addr_b=addr_b, cmd=0x55,
                      payload=bytes([0x00, 0x00, 0x11])).encode()


def parse_status(frame: RS485Frame):
    """Разбор статуса из кадра.

    Не реализовано намеренно. Кадр разбирается полностью — см.
    :meth:`RS485Frame.decode`, — а из регистров расшифрованы только два,
    :data:`KNOWN_REGISTERS`. Собирать из них полноценный статус, дав
    остальным полям правдоподобные имена, пока не на чем: см. docstring
    модуля, там же описан способ расшифровать остальные.
    """
    raise NotDecodedYet(
        "смысл регистров RS485 расшифрован лишь частично (см. "
        "KNOWN_REGISTERS), собирать из них статус целиком пока рано. "
        "Используйте RS485Frame.block — он отдаёт индексы и значения как есть"
    )
